# Which heads each helmet fits over. Every head mesh (a face, mask or hood) and every helmet sit in the same bind-pose
# space, and a helmet is a thin shell (~2 cm) over the skull, so a bulky head (goggles, filters, ear pieces) pokes
# straight through a tight one: the "two helmets merged into each other" look on bots. A head vertex pokes through when,
# in a direction the helmet covers (seen from the middle of the head), it lies further out than the helmet's outside.
# A pair fits with at most max(FLOOR, best * SLACK) such vertices, `best` being the helmet's best head (a few tight
# helmets clip a little on every head).
#   make_headfit.py   reads the cooked meshes from the game's pak, writes mods/PvEDirector/Scripts/headfit.lua
import os
import re
import sys
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'female'))
import make_female as mf  # noqa: E402  (pak access: get / buffers)
from make_female import ROOT  # noqa: E402

# Item row -> helmet mesh (bridge/t_allgear.lua: the game's kit step dressing a bot in every row).
HELMETS = {
    'BABeret': 'SAS_Beret_Skel_02', 'BAHeavyHelmet': 'BA_Helmet_Heavy_Skel_01', 'BAHelmet': 'BA_Helmet_Skel_01',
    'BaronCap': 'Baron_Cap_Skel_01', 'BrodieHelmet': 'Brodie_Helmet_Skel_01', 'CivilianHelmet': 'Civilian_Helmet_Skel_01',
    'ClothCap': 'Cloth_Cap_Skel_01', 'CommandoCap': 'Commando_Cap_Skel_01', 'CustomPSHHelmet': 'Custom_PSH_Helmet_Skel_01',
    'GuildBeret': 'Guild_Beret_Skel_01', 'GuildHelmet': 'Guild_Helmet_Skel_01', 'HeavyM1Helmet': 'HeavyM1_Helmet_Skel_01',
    'HeavyPilotHelmet': 'Heavy_Pilot_Helmet_Skel_01', 'HeavyRiotHelmet': 'Heavy_Riot_Helmet_Skel_01',
    'HeavyStahlhelmHelmet': 'Heavy_Stahlhelm_Skel_01', 'LeatherCap': 'LeatherCap_Skel_01', 'M1Helmet': 'M1_Helmet_Skel_01',
    'M5Helmet': 'M5_Helmet_Skel_01', 'PSHHelmet': 'PSH_Helmet_Skel_01', 'PilotHelmet': 'Pilot_Helmet_Skel_01',
    'PirateHelmet': 'Pirate_Helmet_Skel_01', 'PirateHelmetBlue': 'Pirate_Helmet_B_Skel_01',
    'RedStahlhelmHelmet': 'Red_Stahlhelm_Skel_01', 'RiotHelmet': 'Riot_Helmet_Skel_01', 'SASBeret': 'SAS_Beret_Skel_01',
    'SafetyHelmet': 'Safety_Helmet_Skel_01', 'SecurityHelmet': 'Security_Helmet_Skel_01', 'StahlhelmHelmet': 'Stahlhelm_Skel_01',
    'WardenRiotHelmet': 'Warden_Riot_Helmet_Skel_01', 'WeldersMask': 'Welder_Mask_Skel_01',
}
CENTRE = np.array([0, 0, 168.0])  # middle of the head (heads span z ~155-185)
BINS = 36                         # 5 degree direction cells
MARGIN = 0.3                      # cm outside the helmet before a vertex counts
FLOOR, SLACK = 8, 1.5


def verts(folder, name):
    exp = mf.get('RaidGame/Content/Characters/MainPlayer/Meshes/%s/%s' % (folder, name), '.uexp')
    at, n = mf.buffers(bytearray(exp))[0]  # LOD0
    return np.frombuffer(bytes(exp[at:at + n * 12]), dtype='<f4').reshape(-1, 3)


def cells(v):
    d = v - CENTRE
    r = np.linalg.norm(d, axis=1)
    th = np.arccos(np.clip(d[:, 2] / r, -1, 1))
    ph = np.arctan2(d[:, 1], d[:, 0])
    return r, np.minimum((th / np.pi * BINS).astype(int), BINS - 1), ((ph + np.pi) / (2 * np.pi) * 2 * BINS).astype(int) % (2 * BINS)


def main():
    gear = open(os.path.join(ROOT, 'mods/PvEDirector/Scripts/gear.lua')).read()
    heads = re.findall(r'Heads/([A-Za-z_0-9]+)\.', gear)
    hv = {h: cells(verts('Heads', h)) for h in heads}
    lines = []
    for row in sorted(HELMETS):
        r, ti, pi = cells(verts('Accessories', HELMETS[row]))
        outer = np.full((BINS, 2 * BINS), -np.inf)
        np.maximum.at(outer, (ti, pi), r)
        poke = {}
        for h, (r2, t2, p2) in hv.items():
            o = outer[t2, p2]
            poke[h] = int((np.isfinite(o) & (r2 > o + MARGIN)).sum())
        limit = max(FLOOR, min(poke.values()) * SLACK)
        fit = [h for h in heads if poke[h] <= limit]
        print('%-22s %2d heads fit (limit %d)' % (row, len(fit), limit))
        lines.append('    %s = { %s },' % (row, ', '.join('"%s"' % h for h in fit)))
    out = os.path.join(ROOT, 'mods/PvEDirector/Scripts/headfit.lua')
    with open(out, 'w', newline='\n') as f:
        f.write('-- Generated by tools/headfit/make_headfit.py: for each helmet row, the heads (mesh names) it fits over without\n'
                '-- the head poking through. No helmet: any head.\n'
                'return {\n' + '\n'.join(lines) + '\n}\n')


if __name__ == '__main__':
    main()
